def seed_in_background() -> None:
    """Pre-analyse a curated set on first start so the demo case is ready when judges open the page."""
    def run():
        try:
            have = {s["id"] for s in list_samples()}
            ids = [s for s in SEED if s in have]
            if ids:
                analyze(ids, "demo-seed")
        except Exception as e:  # never block startup
            print("demo seed failed:", e)
    threading.Thread(target=run, daemon=True).start()
