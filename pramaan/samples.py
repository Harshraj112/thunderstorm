def list_samples() -> list[dict]:
    out = []
    real = SETS["real"] / "manifest.json"
    if real.exists():
        for m in json.loads(real.read_text()):
            if (SETS["real"] / m["file"]).exists():
                out.append({"id": f"real/{m['file']}", "set": "real", **m})
    exp_p = SETS["synthetic"] / "expected.json"
    exp = json.loads(exp_p.read_text()) if exp_p.exists() else {}
    for sub in ("images", "cctv", "audio"):
        for f in sorted((SETS["synthetic"] / sub).glob("*")) if (SETS["synthetic"] / sub).exists() else []:
            if f.name.startswith("_") or f.name not in exp:
                continue
            title, story = SYNTH.get(f.name, (f.stem, ""))
            out.append({"id": f"synthetic/{sub}/{f.name}", "set": "synthetic", "file": f.name,
                        "kind": KIND.get(f.suffix.lower(), "file"), "tampered": exp[f.name]["tampered"], "title": title,
                        "story": story, "source": "Generated by scripts/make_demo_samples.py", "real": False})
    return out


_sha_cache: dict[tuple[str, float], str] = {}


def _sha(p: Path) -> str:
    key = (str(p), p.stat().st_mtime)
    if key not in _sha_cache:
        from .custody.hashing import hash_file
        _sha_cache[key] = hash_file(p)["sha256"]
    return _sha_cache[key]


def with_status(items: list[dict]) -> list[dict]:
    """Attach the demo-case exhibit (if any) and its verdict so the UI can show results on each sample card."""
    c = db.q1("SELECT id FROM cases WHERE fir_no=?", (DEMO_FIR,))
    if not c:
        return items
    out = []
    for s in items:
        setname, _, rest = s["id"].partition("/")
        ev = db.q1("SELECT id FROM evidence WHERE case_id=? AND sha256=? ORDER BY ingested_at DESC",
                   (c["id"], _sha(SETS[setname] / rest)))
        if ev:
            job = pipeline.latest_job(ev["id"])
            v = db.q1("SELECT category, confidence, total_llr FROM verdicts WHERE job_id=?", (job["id"],)) if job else None
            s = {**s, "evidence_id": ev["id"], "job_status": job and job["status"], "verdict": v}
        out.append(s)
    return out


def showcase() -> dict:
    """The hero exhibit: a spliced photo whose analysis yields a localisation map and a flagged box."""
    want = ["02_spliced_photoshop.jpg"]
    c = db.q1("SELECT id FROM cases WHERE fir_no=?", (DEMO_FIR,))
    for name in want:
        ev = db.q1("SELECT * FROM evidence WHERE case_id=? AND original_filename=?", (c["id"], name)) if c else None
        if not ev:
            continue
        res = pipeline.results(ev["id"])
        if not res.get("verdict"):
            return {"pending": True, "evidence_id": ev["id"]}
        boxes, layer = [], None
        for f in res["findings"]:
            if f["status"] in ("fail", "warn") and (f.get("location") or {}).get("bbox"):
                boxes.append({**f["location"]["bbox"], "label": f["title"]})
            if not layer and f["code"] in ("IMG_GHOST_LOCAL", "IMG_NOISE", "IMG_TRUFOR") and f.get("artifacts"):
                layer = f["artifacts"][0]
        from PIL import Image
        with Image.open(ev["storage_path"]) as im:
            w, h = im.size
        return {"pending": False, "evidence_id": ev["id"], "job_id": res["job"]["id"], "layer": layer,
                "boxes": boxes[:2], "width": w, "height": h, "verdict": res["verdict"]["category"],
                "filename": ev["original_filename"], "sha256": ev["sha256"]}
    return {"pending": True}


def path_of(sample_id: str) -> Path | None:
    for s in list_samples():          # only paths from the manifest – never arbitrary user paths
        if s["id"] == sample_id:
            setname, _, rest = sample_id.partition("/")
            return SETS[setname] / rest
    return None


def thumbnail(sample_id: str) -> Path | None:
    src = path_of(sample_id)
    if not src:
        return None
    d = config.DATA_DIR / "thumbs"
    d.mkdir(parents=True, exist_ok=True)
    out = d / (sample_id.replace("/", "__") + ".png")
    if out.exists():
        return out
    kind = KIND.get(src.suffix.lower())
    if kind == "image":
        from PIL import Image
        im = Image.open(src).convert("RGB")
        im.thumbnail((560, 420))
        im.save(out)
    elif kind == "video":
        subprocess.run(["ffmpeg", "-hide_banner", "-loglevel", "error", "-y", "-ss", "3", "-i", str(src), "-frames:v", "1",
                        "-vf", "scale=560:-2", str(out)], check=True, timeout=60)
    elif kind == "audio":
        _waveform(src, out)
    return out if out.exists() else None


def _waveform(src: Path, out: Path) -> None:
    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt
    import numpy as np
    from .analyzers.audio.io import decode
    x, sr = decode(src, out.parent, 8000)
    n = 280
    k = len(x) // n
    env = np.abs(x[:k * n]).reshape(n, k).max(axis=1)
    env = env / (env.max() + 1e-9)
    fig = plt.figure(figsize=(5.6, 2.4), dpi=100)
    ax = fig.add_axes([0, 0, 1, 1])
    ax.bar(np.arange(n), env, width=0.7, color="#8466FF")
    ax.bar(np.arange(n), -env, width=0.7, color="#8466FF", alpha=0.55)
    ax.set_xlim(-1, n)
    ax.set_ylim(-1.1, 1.1)
    ax.axis("off")
    fig.patch.set_alpha(0)
    fig.savefig(out, transparent=True)
    plt.close(fig)


def demo_case() -> str:
    c = db.q1("SELECT id FROM cases WHERE fir_no=?", (DEMO_FIR,))
    if c:
        return c["id"]
    cid = db.new_id("case")
    db.insert("cases", {"id": cid, "fir_no": DEMO_FIR, "police_station": "PRAMAAN demo laboratory",
                        "io_name": "Judging panel", "title": "Judge demo kit – real and synthetic test exhibits",
                        "created_by": "system", "created_at": db.now()})
    ledger.append(None, "system", "CASE_CREATED", {"case_id": cid, "fir_no": DEMO_FIR})
    caselog.case_created(cid, "system")
    return cid


_lock = threading.Lock()


def analyze(sample_ids: list[str], actor: str) -> dict:
    """Ingest the chosen samples into the demo case and queue analysis. Exhibits already analysed are reused,
    so a judge clicking the same sample again sees results instantly."""
    cid = demo_case()
    items = []
    with _lock:
        for sid in sample_ids:
            p = path_of(sid)
            if not p:
                continue
            from .custody.hashing import hash_file
            sha = hash_file(p)["sha256"]
            ev = db.q1("SELECT * FROM evidence WHERE case_id=? AND sha256=?", (cid, sha))
            job = None
            if not ev:
                with open(p, "rb") as f:
                    ev = pipeline.ingest(cid, p.name, f, actor, exhibit_no=_exhibit_no(sid),
                                         acquisition_source=f"PRAMAAN demo kit ({sid.split('/')[0]})",
                                         device_details=_source_of(sid))
                job = pipeline.submit(ev["id"], actor)
            items.append({"sample_id": sid, "evidence_id": ev["id"], "job_id": job, "reused": job is None})
    return {"case_id": cid, "items": items}


def _exhibit_no(sid: str) -> str:
    """Stable, readable exhibit numbers: real samples keep their R-number, generated ones get G-<type><nn>."""
    setname, _, rest = sid.partition("/")
    name = Path(rest).name
    if setname == "real":
        return name.split("_")[0]
    sub = Path(rest).parts[0] if len(Path(rest).parts) > 1 else "x"
    return f"G-{ {'images': 'P', 'cctv': 'V', 'audio': 'A'}.get(sub, 'X') }{name[:2]}"


def _source_of(sid: str) -> str | None:
    for s in list_samples():
        if s["id"] == sid:
            return s.get("source")
    return None


